#!/usr/bin/env python3
"""Build and verify the ART-001 Roblox Studio Command Bar installer.

The installer (InstallSlimeV1.luau) embeds the three ART-001 ModuleScripts so it can be
pasted into Studio as one self-contained file. This tool is the only supported way to
produce it, and it checks repository parity, which the installer itself cannot do in Studio.

Usage (from anywhere; paths are resolved from the repository root):

    python3 art/enemies/slime/source/build_installer.py            # verify (default)
    python3 art/enemies/slime/source/build_installer.py --write    # regenerate, then verify
    python3 art/enemies/slime/source/build_installer.py --self-test

Verify fails (exit code 1) unless all of these hold:
  1. Each embedded source in InstallSlimeV1.luau is byte-for-byte identical to its repository
     file (extracted independently of the generator template).
  2. The SHA-256 of each embedded source equals the SHA-256 of its repository file and the
     value recorded in SOURCE_SHA256.txt.
  3. EXPECTED_LENGTHS in the installer equals each file's byte length.
  4. Regenerating the installer from the repository files reproduces InstallSlimeV1.luau
     exactly, so the non-source parts of the installer were not edited by hand either.

--self-test applies same-length edits in memory (to a source file, to an embedded copy and to
the manifest) and confirms that verification rejects every one of them.

Standard library only. Line endings must be LF: on Windows, check out with core.autocrlf=false.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
INSTALLER_PATH = "art/enemies/slime/source/InstallSlimeV1.luau"
MANIFEST_PATH = "art/enemies/slime/source/SOURCE_SHA256.txt"
MODULES = [
    ("VisualPalette", "src/ReplicatedStorage/Shared/Visuals/VisualPalette.luau"),
    ("SlimeModelFactory", "src/ReplicatedStorage/Shared/Visuals/SlimeModelFactory.luau"),
    ("SlimePreview", "src/ServerStorage/EmberDev/SlimePreview.luau"),
]
BRACKET_LEVEL = 12  # long-string level used for the embedded sources: [============[ ... ]============]

HEADER = """--[[
\tEmberbound ART-001: Standard Slime V1 installer (Roblox Studio Command Bar)

\tCreates ONLY these three ModuleScripts and the folders that hold them:
\t  ReplicatedStorage > Shared > Visuals > VisualPalette
\t  ReplicatedStorage > Shared > Visuals > SlimeModelFactory
\t  ServerStorage > EmberDev > SlimePreview
\tIt changes nothing else: no gameplay scripts, RemoteEvents, settings or parts.
\tIf any of the three already exists it stops without changing anything, unless
\tyou set REPLACE_EXISTING_ART to true below (that replaces only these three).

\tRun it in Edit mode (not during Play): open the Command Bar, paste this whole
\tfile, press Enter, then read the Output window.

\tGenerated by art/enemies/slime/source/build_installer.py from the repository
\tfiles; do not edit by hand. In Studio this installer can only confirm that each
\tmodule now holds the text embedded below. Parity between the embedded text and
\tthe repository files is checked outside Studio by build_installer.py
\t(byte-for-byte and SHA-256; see SOURCE_SHA256.txt next to this file).
]]

local REPLACE_EXISTING_ART = false

local ART_SOURCES = {}
"""

BODY = """
(function()
\tlocal PREFIX = "[ART-001 installer]"
\t-- Require Edit mode itself: a paused playtest reports IsRunning() = false as well as IsEdit() = false.
\tlocal RunService = game:GetService("RunService")
\tif not RunService:IsEdit() then
\t\tlocal how = if RunService:IsRunning() then "it is running" else "it is paused"
\t\twarn(PREFIX, `Stop the playtest first ({how}); run the installer in Edit mode. Nothing was changed.`)
\t\treturn
\tend

\tlocal ReplicatedStorage = game:GetService("ReplicatedStorage")
\tlocal ServerStorage = game:GetService("ServerStorage")
\tlocal shared = ReplicatedStorage:FindFirstChild("Shared")
\tif shared == nil or not shared:IsA("Folder") then
\t\twarn(PREFIX, "ReplicatedStorage.Shared was not found. Open the Emberbound place first. Nothing was changed.")
\t\treturn
\tend

\tlocal targets = {
\t\t{ name = "VisualPalette", parent = shared, folder = "Visuals", path = "ReplicatedStorage.Shared.Visuals" },
\t\t{ name = "SlimeModelFactory", parent = shared, folder = "Visuals", path = "ReplicatedStorage.Shared.Visuals" },
\t\t{ name = "SlimePreview", parent = ServerStorage, folder = "EmberDev", path = "ServerStorage.EmberDev" },
\t}

\t-- Check everything before changing anything.
\tlocal existing = {}
\tfor _, target in targets do
\t\tlocal holder = target.parent:FindFirstChild(target.folder)
\t\tif holder ~= nil and not holder:IsA("Folder") then
\t\t\twarn(PREFIX, `{target.path} exists but is a {holder.ClassName}, not a Folder. Nothing was changed.`)
\t\t\treturn
\t\tend
\t\tlocal current = if holder then holder:FindFirstChild(target.name) else nil
\t\tif current ~= nil then
\t\t\tif not current:IsA("ModuleScript") then
\t\t\t\twarn(PREFIX, `{target.path}.{target.name} exists but is a {current.ClassName}. Nothing was changed.`)
\t\t\t\treturn
\t\t\tend
\t\t\ttable.insert(existing, `{target.path}.{target.name}`)
\t\tend
\tend
\tif #existing > 0 and not REPLACE_EXISTING_ART then
\t\twarn(PREFIX, "Already installed: " .. table.concat(existing, ", "))
\t\twarn(PREFIX, "Nothing was changed. To replace just these modules, set REPLACE_EXISTING_ART = true at the top and run again.")
\t\treturn
\tend

\tfor _, target in targets do
\t\tlocal holder = target.parent:FindFirstChild(target.folder)
\t\tif holder == nil then
\t\t\tholder = Instance.new("Folder")
\t\t\tholder.Name = target.folder
\t\t\tholder.Parent = target.parent
\t\tend
\t\tlocal module = holder:FindFirstChild(target.name)
\t\tif module == nil then
\t\t\tmodule = Instance.new("ModuleScript")
\t\t\tmodule.Name = target.name
\t\t\tmodule.Parent = holder
\t\tend
\t\tmodule.Source = ART_SOURCES[target.name]
\tend

\t-- Embedded-source check (Studio): each module must now hold exactly the text embedded in this
\t-- installer, at the length recorded when it was generated. This does not compare against the
\t-- repository; that is the separate offline check in build_installer.py.
\tlocal allIntact = true
\tfor _, target in targets do
\t\tlocal module = target.parent:FindFirstChild(target.folder):FindFirstChild(target.name)
\t\tlocal length = #module.Source
\t\tlocal intact = module.Source == ART_SOURCES[target.name] and length == EXPECTED_LENGTHS[target.name]
\t\tallIntact = allIntact and intact
\t\tprint(PREFIX, `{target.path}.{target.name}: {length} characters`, if intact then "(embedded text installed intact)" else "(MISMATCH)")
\tend
\tif allIntact then
\t\tprint(PREFIX, "Installed 3 ModuleScripts. Nothing else was changed.")
\t\tprint(PREFIX, "Next, paste this into the Command Bar:  require(game.ServerStorage.EmberDev.SlimePreview).check()")
\telse
\t\twarn(PREFIX, "A module does not hold the embedded text. Report this before testing.")
\tend
end)()
"""


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def check_source_text(name: str, data: bytes) -> list[str]:
    problems = []
    if b"\r" in data:
        problems.append(f"{name}: contains CR line endings; the installer and SHA-256 values are defined for LF")
    if not data.endswith(b"\n"):
        problems.append(f"{name}: must end with a newline")
    if f"]{'=' * BRACKET_LEVEL}]".encode() in data:
        problems.append(f"{name}: contains the installer's long-string terminator; raise BRACKET_LEVEL")
    try:
        data.decode("utf-8")
    except UnicodeDecodeError:
        problems.append(f"{name}: is not valid UTF-8")
    return problems


def build_installer(sources: dict[str, bytes]) -> bytes:
    """The installer text for these module sources (deterministic)."""
    eq = "=" * BRACKET_LEVEL
    out = [HEADER.encode()]
    for name, _ in MODULES:
        out.append(f'ART_SOURCES["{name}"] = [{eq}[\n'.encode())
        out.append(sources[name])  # Luau drops the newline right after [==[, so the string equals the file
        out.append(f"]{eq}]\n".encode())
    out.append(b"\nlocal EXPECTED_LENGTHS = {\n")
    for name, _ in MODULES:
        out.append(f"\t{name} = {len(sources[name])},\n".encode())
    out.append(b"}\n")
    out.append(BODY.encode())
    return b"".join(out)


def build_manifest(sources: dict[str, bytes]) -> str:
    """SOURCE_SHA256.txt in sha256sum format (check with: sha256sum -c <file> from the repo root)."""
    return "".join(f"{sha256(sources[name])}  {path}\n" for name, path in MODULES)


def extract_embedded(installer: bytes) -> tuple[dict[str, bytes], dict[str, int]]:
    """Embedded sources and EXPECTED_LENGTHS read straight from the installer text."""
    embedded: dict[str, bytes] = {}
    for match in re.finditer(rb'ART_SOURCES\["(\w+)"\] = \[(=*)\[\n(.*?)\]\2\]', installer, re.S):
        name = match.group(1).decode()
        if name in embedded:
            raise ValueError(f"installer embeds {name} twice")
        embedded[name] = match.group(3)
    lengths: dict[str, int] = {}
    block = re.search(rb"local EXPECTED_LENGTHS = \{\n(.*?)\n\}", installer, re.S)
    if block:
        for line in block.group(1).splitlines():
            m = re.fullmatch(rb"\s*(\w+) = (\d+),?", line)
            if m:
                lengths[m.group(1).decode()] = int(m.group(2))
    return embedded, lengths


def parse_manifest(text: str) -> dict[str, str]:
    entries: dict[str, str] = {}
    for line in text.splitlines():
        m = re.fullmatch(r"([0-9a-f]{64})  (\S+)", line)
        if not m:
            raise ValueError(f"bad manifest line: {line!r}")
        entries[m.group(2)] = m.group(1)
    return entries


def verify(sources: dict[str, bytes], installer: bytes, manifest_text: str, report: bool = True) -> list[str]:
    """All parity problems (empty list = verified)."""
    problems: list[str] = []
    say = print if report else (lambda *_: None)
    for name, data in sources.items():
        problems += check_source_text(name, data)
    try:
        embedded, lengths = extract_embedded(installer)
    except ValueError as error:
        return problems + [str(error)]
    try:
        manifest = parse_manifest(manifest_text)
    except ValueError as error:
        problems.append(str(error))
        manifest = {}

    expected_names = [name for name, _ in MODULES]
    if sorted(embedded) != sorted(expected_names):
        problems.append(f"installer embeds {sorted(embedded)}, expected {sorted(expected_names)}")
    if sorted(manifest) != sorted(path for _, path in MODULES):
        problems.append(f"{MANIFEST_PATH} lists {sorted(manifest)}, expected the three module paths")

    for name, path in MODULES:
        data = sources[name]
        file_hash = sha256(data)
        copy = embedded.get(name)
        copy_hash = sha256(copy) if copy is not None else "-"
        identical = copy == data
        length_ok = lengths.get(name) == len(data)
        manifest_ok = manifest.get(path) == file_hash
        say(f"  {path}")
        say(f"    repository file  {len(data):>6} bytes  sha256 {file_hash}")
        say(f"    embedded copy    {len(copy) if copy is not None else '-':>6} bytes  sha256 {copy_hash}")
        say(f"    byte-identical: {'yes' if identical else 'NO'}   EXPECTED_LENGTHS: {'ok' if length_ok else 'WRONG'}"
            f"   manifest: {'ok' if manifest_ok else 'WRONG'}")
        if not identical:
            problems.append(f"{name}: embedded copy differs from {path}")
        if not length_ok:
            problems.append(f"{name}: EXPECTED_LENGTHS is {lengths.get(name)}, file has {len(data)} bytes")
        if not manifest_ok:
            problems.append(f"{name}: {MANIFEST_PATH} records {manifest.get(path)}, file hashes to {file_hash}")

    if all(name in sources for name in expected_names):
        regenerated = build_installer(sources)
        if regenerated != installer:
            problems.append("InstallSlimeV1.luau differs from a fresh build (edited by hand or stale); run --write")
            new_lines, old_lines = regenerated.split(b"\n"), installer.split(b"\n")
            for number, (new, old) in enumerate(zip(new_lines, old_lines), start=1):
                if new != old:
                    problems.append(f"  first difference at installer line {number}")
                    break
        else:
            say("  regenerated installer matches InstallSlimeV1.luau byte-for-byte")
    return problems


def read_sources() -> dict[str, bytes]:
    return {name: (ROOT / path).read_bytes() for name, path in MODULES}


def same_length_edit(data: bytes) -> bytes:
    """Change one digit without changing the length."""
    index = next(i for i, b in enumerate(data) if chr(b).isdigit())
    digit = data[index : index + 1]
    return data[:index] + (b"1" if digit != b"1" else b"2") + data[index + 1 :]


def self_test() -> list[str]:
    sources = read_sources()
    installer = build_installer(sources)
    manifest = build_manifest(sources)
    failures = []
    if verify(sources, installer, manifest, report=False):
        failures.append("a freshly built installer did not verify")
    cases = []
    for name, _ in MODULES:
        edited = dict(sources)
        edited[name] = same_length_edit(sources[name])
        assert len(edited[name]) == len(sources[name])
        cases.append((f"same-length edit to repository file {name}", edited, installer, manifest))
        start = installer.index(f'ART_SOURCES["{name}"]'.encode())
        cut = installer.index(b"\n", start) + 1
        tampered = installer[:cut] + same_length_edit(installer[cut:])
        cases.append((f"same-length edit to the embedded copy of {name}", sources, tampered, manifest))
    body_edit = installer.replace(b"Nothing was changed.", b"Nothing was edited.", 1)
    cases.append(("edit to the installer outside the embedded sources", sources, body_edit, manifest))
    manifest_edit = manifest.replace(manifest[0], "f" if manifest[0] != "f" else "e", 1)
    cases.append(("edit to SOURCE_SHA256.txt", sources, installer, manifest_edit))
    for label, s, i, m in cases:
        caught = bool(verify(s, i, m, report=False))
        print(f"  {'rejected' if caught else 'NOT REJECTED'}: {label}")
        if not caught:
            failures.append(label)
    return failures


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--write", action="store_true", help="regenerate the installer and SOURCE_SHA256.txt, then verify")
    parser.add_argument("--self-test", action="store_true", help="confirm that same-length edits are rejected")
    args = parser.parse_args()

    if args.self_test:
        print("ART-001 installer tool self-test")
        failures = self_test()
        print("SELF-TEST PASSED" if not failures else f"SELF-TEST FAILED: {failures}")
        return 0 if not failures else 1

    sources = read_sources()
    if args.write:
        problems = [p for name, data in sources.items() for p in check_source_text(name, data)]
        if problems:
            print("\n".join(problems))
            return 1
        (ROOT / INSTALLER_PATH).write_bytes(build_installer(sources))
        (ROOT / MANIFEST_PATH).write_bytes(build_manifest(sources).encode())
        print(f"wrote {INSTALLER_PATH} and {MANIFEST_PATH}")

    print("ART-001 installer parity (repository files vs InstallSlimeV1.luau)")
    problems = verify(sources, (ROOT / INSTALLER_PATH).read_bytes(), (ROOT / MANIFEST_PATH).read_text())
    if problems:
        print("PARITY FAILED")
        print("\n".join(f"  - {p}" for p in problems))
        return 1
    print("PARITY VERIFIED: all three embedded sources are byte-identical to the repository files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
